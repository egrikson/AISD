def read(dataset: str, filename: str) -> pd.DataFrame:
    """Читает таблицу результатов для указанного датасета."""
    return pd.read_csv(RESULTS_DIR / dataset / filename)


def read_text(dataset: str, filename: str) -> str:
    return (RESULTS_DIR / dataset / filename).read_text(encoding="utf-8")


def table(frame: pd.DataFrame, columns: dict[str, str] | None = None) -> str:
    """Преобразует DataFrame в таблицу Markdown."""
    if columns:
        frame = frame[list(columns)].rename(columns=columns)
    header = "| " + " | ".join(str(c) for c in frame.columns) + " |"
    separator = "|" + "|".join("---" for _ in frame.columns) + "|"
    rows = [
        "| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |"
        for row in frame.itertuples(index=False)
    ]
    return "\n".join([header, separator, *rows])


def source_of(obj: object) -> str:
    """Исходный код объекта без декоратора ``@dataclass`` и пустых строк подряд."""
    code = inspect.getsource(obj)
    code = re.sub(r"\n{3,}", "\n\n", code)
    return code.rstrip()


